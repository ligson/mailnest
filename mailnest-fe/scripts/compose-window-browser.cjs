  await popup.setViewportSize({width:390,height:844}); await popup.waitForTimeout(200);
  await popup.screenshot({path:'output/playwright/compose-window-mobile.png'});
  if(await popup.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)) throw Error('手机横向溢出');
  const footer = await standalone.locator('.compose-footer').boundingBox();
  if(footer.y+footer.height>845) throw Error('手机发送按钮超出屏幕');
